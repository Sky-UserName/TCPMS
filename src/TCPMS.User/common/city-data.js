// 城市名归一：定位结果可能是「郑州」或「河南省」，统一成「郑州市」这种写法。
export const normalizeCityName = (name) => {
	const value = String(name || '').trim()
	if (!value) return ''
	if (/(省|自治区|特别行政区)$/.test(value)) return ''
	if (/[市州盟县区]$/.test(value)) return value
	return `${value}市`
}

// 定位城市兜底：把「郑州市」这类值插到热门城市最前面，保证在下拉里能看到。
export const buildHotCities = (locatedCity = '') => {
	const city = String(locatedCity || '').trim()
	if (!city) return HOT_CITIES.slice()
	return [city, ...HOT_CITIES.filter((item) => item !== city)]
}
